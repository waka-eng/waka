/**
 * Drizzle ORM schema — Group Top of Mind boards.
 *
 * A `group` is a small board that pools its members' *shared* inspirations into
 * a synthesized Top of Mind. Membership is by shareable `join_code`. This is the
 * clean boards model introduced by US-052 and is intentionally separate from the
 * US-051 `group_conversation_rooms` tables, which model chat rooms and are left
 * untouched.
 *
 * Whether a given inspiration feeds these boards is controlled by
 * `signals.shared_to_groups` (see schema.ts) — shared by default, flip to private.
 */

import { relations } from "drizzle-orm";
import {
  foreignKey,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { signals, users } from "./schema";
import { wowKindEnum } from "./schema-wow-moments";

export const groups = pgTable(
  "groups",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    ownerUserId: uuid("owner_user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    // Opaque, human-shareable code embedded in the join link. Unique so a code
    // resolves to exactly one group.
    joinCode: text("join_code").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => ({
    joinCodeUnique: uniqueIndex("groups_join_code_unique_idx").on(table.joinCode),
    ownerIdx: index("groups_owner_idx").on(table.ownerUserId),
  }),
);

export const groupMembers = pgTable(
  "group_members",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    groupId: uuid("group_id")
      .notNull()
      .references(() => groups.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    // "owner" for the creator, "member" for everyone who joined by link.
    role: text("role").notNull().default("member"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => ({
    // A user belongs to a group at most once; also the hot lookup path for
    // "which groups am I in".
    groupUserUnique: uniqueIndex("group_members_group_user_unique_idx").on(
      table.groupId,
      table.userId,
    ),
    userIdx: index("group_members_user_idx").on(table.userId),
  }),
);

/**
 * A Group Top of Mind note (US-053). Unlike single-user `top_of_mind_notes`,
 * this belongs to the GROUP, not one user, so its evidence can span members.
 * Generated by running the existing Top of Mind judge over the pooled shared
 * inspirations of all members.
 */
export const groupTopOfMindNotes = pgTable(
  "group_top_of_mind_notes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    groupId: uuid("group_id")
      .notNull()
      .references(() => groups.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    kind: wowKindEnum("kind").notNull(),
    idempotencyKey: text("idempotency_key").notNull(),
    why: text("why").notNull(),
    beliefStatement: text("belief_statement"),
    reflectionQuestion: text("reflection_question"),
    reflectionGuide: text("reflection_guide"),
    locale: text("locale").notNull().default("en-US"),
    wowScore: integer("wow_score").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    groupIdempotencyKeyUnique: uniqueIndex(
      "group_top_of_mind_notes_group_idempotency_key_unique_idx",
    ).on(table.groupId, table.idempotencyKey),
    groupCreatedIdx: index("group_top_of_mind_notes_group_created_idx").on(
      table.groupId,
      table.createdAt.desc(),
    ),
  }),
);

/**
 * Evidence for a group note. Each row records both the signal AND the member who
 * owns it (`owner_user_id`), so the board can tag every inspiration with whose
 * it is. The composite FK ties the pair back to a real (signal, owner) row.
 */
export const groupTopOfMindNoteSignals = pgTable(
  "group_top_of_mind_note_signals",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    groupTopOfMindNoteId: uuid("group_top_of_mind_note_id")
      .notNull()
      .references(() => groupTopOfMindNotes.id, { onDelete: "cascade" }),
    signalId: uuid("signal_id")
      .notNull()
      .references(() => signals.id, { onDelete: "cascade" }),
    ownerUserId: uuid("owner_user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    role: text("role").notNull().default("related"),
    reason: text("reason").notNull().default(""),
    sortOrder: integer("sort_order").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    noteOrderIdx: index("group_top_of_mind_note_signals_note_order_idx").on(
      table.groupTopOfMindNoteId,
      table.sortOrder,
    ),
    noteSignalUnique: uniqueIndex(
      "group_top_of_mind_note_signals_note_signal_unique_idx",
    ).on(table.groupTopOfMindNoteId, table.signalId),
    signalOwnerFk: foreignKey({
      name: "group_top_of_mind_note_signals_signal_owner_fk",
      columns: [table.signalId, table.ownerUserId],
      foreignColumns: [signals.id, signals.userId],
    }).onDelete("cascade"),
  }),
);

export type Group = typeof groups.$inferSelect;
export type NewGroup = typeof groups.$inferInsert;
export type GroupMember = typeof groupMembers.$inferSelect;
export type NewGroupMember = typeof groupMembers.$inferInsert;
export type GroupTopOfMindNoteRow = typeof groupTopOfMindNotes.$inferSelect;
export type NewGroupTopOfMindNoteRow = typeof groupTopOfMindNotes.$inferInsert;
export type GroupTopOfMindNoteSignalRow = typeof groupTopOfMindNoteSignals.$inferSelect;
export type NewGroupTopOfMindNoteSignalRow = typeof groupTopOfMindNoteSignals.$inferInsert;

export const groupTopOfMindNotesRelations = relations(
  groupTopOfMindNotes,
  ({ one, many }) => ({
    group: one(groups, {
      fields: [groupTopOfMindNotes.groupId],
      references: [groups.id],
    }),
    evidence: many(groupTopOfMindNoteSignals),
  }),
);

export const groupTopOfMindNoteSignalsRelations = relations(
  groupTopOfMindNoteSignals,
  ({ one }) => ({
    note: one(groupTopOfMindNotes, {
      fields: [groupTopOfMindNoteSignals.groupTopOfMindNoteId],
      references: [groupTopOfMindNotes.id],
    }),
    signal: one(signals, {
      fields: [groupTopOfMindNoteSignals.signalId],
      references: [signals.id],
    }),
    owner: one(users, {
      fields: [groupTopOfMindNoteSignals.ownerUserId],
      references: [users.id],
    }),
  }),
);

export const groupsRelations = relations(groups, ({ one, many }) => ({
  owner: one(users, {
    fields: [groups.ownerUserId],
    references: [users.id],
  }),
  members: many(groupMembers),
}));

export const groupMembersRelations = relations(groupMembers, ({ one }) => ({
  group: one(groups, {
    fields: [groupMembers.groupId],
    references: [groups.id],
  }),
  user: one(users, {
    fields: [groupMembers.userId],
    references: [users.id],
  }),
}));
