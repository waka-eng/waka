-- Proving an email address is not a thing this product asks for any more.
--
-- 0006 added `accounts.email_verified_at` and `email_verifications`, and made
-- joining a group wait for a proven address. The proof was never obtainable:
-- the transport was deliberately left as an interface with a console-logging
-- default, and no provider was ever wired. So the link nobody received gated
-- the one act that needed it, and every account created before 0006 — none of
-- which had anything to prove at the time — could join nothing at all.
--
-- The two honest ways out were to wire a mail provider, or to mark the
-- pre-existing accounts verified and gate only new signups. The product owner
-- chose a third: drop the requirement. Joining a group now stands on the join
-- code alone, which is a bearer credential rotated when someone is removed.
--
-- WHY THIS DROPS THE SCHEMA INSTEAD OF LEAVING IT DEAD.
--
--   * `email_verifications` is a table of bearer credentials. With the code
--     that issued, expired and spent them gone, live rows would sit there
--     unexpirable and unspendable, and a leaked backup would still be a list
--     of hashes nobody is watching. Dead security state is worse than none.
--   * `packages/api/src/db/index.ts` is the schema source of truth for
--     drizzle-kit. Leaving the objects behind puts the database permanently
--     out of step with it, and the next person to run `pnpm db:generate` gets
--     a destructive diff written by a tool, with no reason attached — which is
--     this file, only anonymous.
--
-- 0006 is not edited or reverted; it stays as the record of what was tried.
-- Re-adding any of this means choosing a provider and a sending domain FIRST,
-- and deciding what happens to the accounts that already exist.
--
-- NOT AFFECTED: the Google `email_verified` ID-token claim checked in
-- routes/auth-google.ts. That is Google attesting an address it owns the
-- proof of, and it is the live defence against account pre-hijacking. It has
-- nothing to do with the columns below.
DROP TABLE IF EXISTS email_verifications;

ALTER TABLE accounts DROP COLUMN IF EXISTS email_verified_at;
